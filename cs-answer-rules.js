// 고객 글 → [{name, score}] 점수순 (0점 제외). context = 같은 채팅의 그 전 고객 글(하루 안) — "네 맞습니다"처럼 앞 글이 있어야 뜻이 통하는 경우용, 반 점수.
function csRank(text, context = '') {
  const s = {};
  const add = (n, v) => { s[n] = (s[n] || 0) + v; };
  const score = (t, k) => {
    for (const [n, res] of [...Object.entries(CS_RULES.R), ...Object.entries(CS_RULES.L)]) for (const r of res) { const [re, w] = Array.isArray(r) ? r : [r, 2]; if (re.test(t)) add(n, w * k); }
    for (const [re, names] of Object.values(CS_RULES.T)) if (re.test(t)) names.forEach((n) => add(n, k));
  };
  score(text, 1);
  if (context) score(context, 0.5);
  return Object.entries(s).map(([name, score]) => ({ name, score: score + (CS_RULES.P[name] || 0) / 100 }))
    .sort((a, b) => b.score - a.score);
}
