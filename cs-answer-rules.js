// 고객 글 → [{name, score}] 점수순 (0점 제외). 숫자 가린 글에도 동작.
function csRank(text) {
  const s = {};
  const add = (n, v) => { s[n] = (s[n] || 0) + v; };
  for (const [n, res] of Object.entries(CS_RULES.R)) for (const re of res) if (re.test(text)) add(n, 2);
  for (const [re, names] of Object.values(CS_RULES.T)) if (re.test(text)) names.forEach((n) => add(n, 1));
  return Object.entries(s).map(([name, score]) => ({ name, score: score + (CS_RULES.P[name] || 0) / 100 }))
    .sort((a, b) => b.score - a.score);
}
