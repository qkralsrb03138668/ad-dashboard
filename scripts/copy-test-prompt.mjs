/* 쇼핑몰 후기 — 상품 페이지가 부르는 공개 주소(게시판 4번)에서 최근 것부터. 자동 문장은 뺀다. 실패하면 빈 배열 */
const AUTO = /^(만족할 만큼 좋은 상품|완전 최고에요|잘 산 것 같아|저와는 맞지 않는|생각한 그대로)/;
export async function shopReviews(no, max = 40) {
  const UA = { 'User-Agent': 'Mozilla/5.0' }, page = `https://danarobe.com/product/detail.html?product_no=${no}`, ids = new Set();
  try {
    for (let p = 1; p <= 6 && ids.size < max; p++) {
      const h = await (await fetch(`${page}&page_4=${p}`, { headers: UA })).text(), before = ids.size;
      for (const m of h.matchAll(/board\/product\/4\?no=(\d+)|no=(\d+)&board_no=4/g)) ids.add(m[1] || m[2]);
      if (ids.size === before) break;
    }
    const out = [];
    for (const id of [...ids].slice(0, max)) {
      try {
        const r = await fetch(`https://danarobe.com/exec/front/board/product/4?no=${id}&board_no=4&spread_flag=T&pass_check=F`, { headers: { ...UA, 'X-Requested-With': 'XMLHttpRequest', Referer: page } });
        const t = String((await r.json()).read?.content || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
        if (t && !AUTO.test(t)) out.push(t.slice(0, 300));
      } catch { /* 한 건 실패는 건너뜀 */ }
    }
    return out;
  } catch { return []; }
}
