/* 저장 직전 정리: 빈 줄은 하나로, 18자 넘는 줄은 마지막 공백에서 끊는다(단어 중간에서는 안 끊음). 서버·로컬 스크립트 공용 */
export const COPY_MAX_LINE = 18;
export function tidyCopy(text: string, max = COPY_MAX_LINE): string {
  const out: string[] = [];
  for (const raw of String(text).replace(/\r/g, "").split("\n")) {
    let line = raw.trimEnd();
    while ([...line].length > max) {
      const chars = [...line];
      let cut = -1;
      for (let i = Math.min(max, chars.length - 1); i > 0; i--) if (chars[i] === " ") { cut = i; break; }
      if (cut <= 0) break;                       // 공백이 없으면 그대로 둔다
      out.push(chars.slice(0, cut).join("").trimEnd());
      line = chars.slice(cut + 1).join("").trimStart();
    }
    out.push(line);
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}
